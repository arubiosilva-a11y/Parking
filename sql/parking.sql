-- Esquema inicial de ParkControl para una base PostgreSQL existente.
-- Ejecutar una vez en un esquema parking vacío, con codificación UTF-8.
BEGIN;

CREATE SCHEMA IF NOT EXISTS parking;
SET LOCAL search_path TO parking, pg_catalog;

CREATE TABLE abonado (
    id_abonado integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre varchar(255),
    email varchar(255),
    matricula varchar(255),
    fecha_ini timestamp without time zone,
    fecha_fin timestamp without time zone
);

CREATE TABLE plaza (
    id_plaza integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    num integer,
    planta integer,
    tipo varchar(255),
    estado varchar(255)
);

CREATE TABLE tarifa (
    id_tarifa integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    precio_min numeric,
    min_cortesia integer,
    horas_maximas integer,
    fecha_aplicacion timestamp without time zone
);

CREATE TABLE promocion (
    id_promocion integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre varchar(255),
    tipo varchar(255),
    min_descuento numeric
);

CREATE TABLE usuario (
    id_usuario integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre varchar(255) NOT NULL,
    email varchar(255) NOT NULL,
    "contraseña" varchar(255) NOT NULL,
    rol varchar(255) NOT NULL,
    id_abonado integer REFERENCES abonado (id_abonado),
    CONSTRAINT usuario_rol_valido CHECK (rol IN ('ADMIN', 'OPERADOR', 'ABONADO')),
    CONSTRAINT usuario_abonado_requerido CHECK (rol <> 'ABONADO' OR id_abonado IS NOT NULL),
    CONSTRAINT usuario_abonado_unico UNIQUE (id_abonado)
);

CREATE UNIQUE INDEX usuario_email_ci_unico ON usuario (lower(email));

CREATE TABLE activacion_abonado (
    id_abonado integer PRIMARY KEY REFERENCES abonado (id_abonado) ON DELETE CASCADE,
    codigo_hash varchar(64) NOT NULL UNIQUE,
    expira_en timestamp with time zone NOT NULL
);

CREATE TABLE ticket (
    id_ticket integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    matricula varchar(255),
    hora_entrada timestamp without time zone,
    hora_salida timestamp without time zone,
    minutos integer,
    descuento numeric,
    importe numeric,
    importe_descuento numeric,
    estado varchar(255),
    id_plaza integer REFERENCES plaza (id_plaza),
    id_abonado integer REFERENCES abonado (id_abonado),
    id_tarifa integer REFERENCES tarifa (id_tarifa),
    id_promocion integer REFERENCES promocion (id_promocion)
);

CREATE TABLE descuento (
    id_descuento integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_ticket integer NOT NULL REFERENCES ticket (id_ticket),
    id_promocion integer NOT NULL REFERENCES promocion (id_promocion),
    minutos numeric(19, 2) NOT NULL,
    aplicado_en timestamp without time zone NOT NULL,
    CONSTRAINT uq_descuento_ticket_promocion UNIQUE (id_ticket, id_promocion)
);

COMMIT;
